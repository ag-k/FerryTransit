#!/usr/bin/env node

import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { dirname, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT_FILES = new Set([
  '200.html',
  '404.html',
  'apple-touch-icon.png',
  'favicon.ico',
  'index.html'
])

const isPrecacheTarget = (relativePath) => {
  return ROOT_FILES.has(relativePath)
    || relativePath.startsWith('_nuxt/')
    || relativePath.startsWith('css/')
}

export function collectPrecacheFiles(outputRoot) {
  if (!existsSync(outputRoot)) {
    throw new Error(`静的成果物が見つかりません: ${outputRoot}`)
  }

  const files = []
  const visit = (directory) => {
    for (const entry of readdirSync(directory)) {
      const fullPath = resolve(directory, entry)
      if (statSync(fullPath).isDirectory()) {
        visit(fullPath)
        continue
      }

      const relativePath = relative(outputRoot, fullPath).split('\\').join('/')
      if (isPrecacheTarget(relativePath)) {
        files.push(relativePath)
      }
    }
  }

  visit(outputRoot)
  return files.sort()
}

export function createServiceWorkerSource(outputRoot, relativeFiles) {
  const revision = createHash('sha256')
  for (const relativeFile of relativeFiles) {
    revision.update(relativeFile)
    revision.update(readFileSync(resolve(outputRoot, relativeFile)))
  }

  const cacheName = `ferry-transit-shell-${revision.digest('hex').slice(0, 12)}`
  const precacheUrls = relativeFiles.map(relativeFile => `/${relativeFile}`)

  return `/* This file is generated by scripts/generate-service-worker.mjs. */
const CACHE_PREFIX = 'ferry-transit-shell-'
const CACHE_NAME = ${JSON.stringify(cacheName)}
const PRECACHE_URLS = ${JSON.stringify(precacheUrls, null, 2)}
const PRECACHE_PATHS = new Set(PRECACHE_URLS)

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then(cache => cache.addAll(PRECACHE_URLS))
  )
})

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then(cacheNames => Promise.all(
        cacheNames
          .filter(cacheName => cacheName.startsWith(CACHE_PREFIX) && cacheName !== CACHE_NAME)
          .map(cacheName => caches.delete(cacheName))
      ))
      .then(() => self.clients.claim())
  )
})

const fetchNavigation = async (request) => {
  try {
    const response = await fetch(request)
    if (response.ok) {
      const cache = await caches.open(CACHE_NAME)
      await cache.put('/index.html', response.clone())
    }
    return response
  } catch {
    return (await caches.match('/index.html')) || Response.error()
  }
}

const fetchStaticAsset = async (request) => {
  const cached = await caches.match(request)
  if (cached) return cached

  const response = await fetch(request)
  if (response.ok) {
    const cache = await caches.open(CACHE_NAME)
    await cache.put(request, response.clone())
  }
  return response
}

self.addEventListener('fetch', (event) => {
  if (event.request.method !== 'GET') return

  const url = new URL(event.request.url)
  if (event.request.mode === 'navigate') {
    event.respondWith(fetchNavigation(event.request))
    return
  }

  if (
    url.origin === self.location.origin
    && (PRECACHE_PATHS.has(url.pathname) || url.pathname.startsWith('/_nuxt/') || url.pathname.startsWith('/css/'))
  ) {
    event.respondWith(fetchStaticAsset(event.request))
  }
})
`
}

export function generateServiceWorker(outputRoot) {
  const relativeFiles = collectPrecacheFiles(outputRoot)
  if (!relativeFiles.includes('index.html')) {
    throw new Error(`index.htmlが見つかりません: ${outputRoot}`)
  }

  const outputPath = resolve(outputRoot, 'sw.js')
  mkdirSync(dirname(outputPath), { recursive: true })
  writeFileSync(outputPath, createServiceWorkerSource(outputRoot, relativeFiles))

  return {
    cacheEntries: relativeFiles.length,
    outputPath
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const outputRoot = resolve(process.cwd(), process.argv[2] || '.output/public')
  const result = generateServiceWorker(outputRoot)
  console.log(`Service Worker生成完了: ${result.outputPath} (${result.cacheEntries} files)`)
}
